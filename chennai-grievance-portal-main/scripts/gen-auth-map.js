/**
 * Generates src/components/auth/chennaiMap.ts: a light, static SVG drawing of Chennai's 200 GCC wards (thinned) with the
 * 15 zone centroids, for the sign-in hero. Static so the public sign-in page needs no data call.
 *   node scripts/gen-auth-map.js
 */
const fs = require("fs");
const path = require("path");

const g = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "data", "boundaries", "gcc-wards.geojson"), "utf8"));
const W = 400;
let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
const rings = (geom) => (geom.type === "Polygon" ? geom.coordinates : geom.type === "MultiPolygon" ? geom.coordinates.flat() : []);
for (const f of g.features) for (const r of rings(f.geometry)) for (const [x, y] of r) { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
// equirectangular with the latitude correction, north up
const k = Math.cos(((minY + maxY) / 2) * Math.PI / 180);
const sx = W / ((maxX - minX) * k);
const H = Math.round((maxY - minY) * sx);
const P = ([x, y]) => [((x - minX) * k * sx), ((maxY - y) * sx)];

// Douglas-Peucker thinning in screen pixels
function dp(pts, eps) {
  if (pts.length < 3) return pts;
  let idx = 0, dmax = 0;
  const [ax, ay] = pts[0], [bx, by] = pts[pts.length - 1];
  const L = Math.hypot(bx - ax, by - ay) || 1;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = Math.abs((by - ay) * pts[i][0] - (bx - ax) * pts[i][1] + bx * ay - by * ax) / L;
    if (d > dmax) { dmax = d; idx = i; }
  }
  if (dmax <= eps) return [pts[0], pts[pts.length - 1]];
  return [...dp(pts.slice(0, idx + 1), eps).slice(0, -1), ...dp(pts.slice(idx), eps)];
}

const zones = new Map();
let d = "";
for (const f of g.features) {
  const z = f.properties.zone_number;
  for (const r of rings(f.geometry)) {
    // a closed ring starts and ends on one point, so thin its two halves separately
    const all = r.map(P);
    const mid = Math.floor(all.length / 2);
    const pts = [...dp(all.slice(0, mid + 1), 0.9).slice(0, -1), ...dp(all.slice(mid), 0.9)];
    if (pts.length < 3) continue;
    d += "M" + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L") + "Z";
    const acc = zones.get(z) ?? { name: f.properties.zone_name, x: 0, y: 0, n: 0 };
    for (const [x, y] of pts) { acc.x += x; acc.y += y; acc.n++; }
    zones.set(z, acc);
  }
}
const pins = [...zones.entries()].sort((a, b) => a[0] - b[0]).map(([zone, a]) => ({ zone, name: a.name, x: +(a.x / a.n).toFixed(1), y: +(a.y / a.n).toFixed(1) }));
const out = `/* Generated by scripts/gen-auth-map.js from data/boundaries/gcc-wards.geojson — do not edit by hand. */
export const MAP_W = ${W};
export const MAP_H = ${H};
/** every GCC ward outline, thinned, as one SVG path */
export const WARDS_D = ${JSON.stringify(d)};
/** zone centroids (screen units) */
export const ZONE_PINS: { zone: number; name: string; x: number; y: number }[] = ${JSON.stringify(pins)};
`;
const dir = path.join(__dirname, "..", "src", "components", "auth");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "chennaiMap.ts"), out);
console.log("chennaiMap.ts:", W, "x", H, Math.round(d.length / 1024), "KB path,", pins.length, "zones");
