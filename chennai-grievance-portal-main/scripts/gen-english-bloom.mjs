// Builds src/lib/thunai/english.bloom.ts from the word-list package (274,000 English words): a Bloom filter, about 4 percent false hits,
// so the fast lane (which runs in the browser and cannot read a file) can tell "tomorrow" from "Kumbakonam" (QA pass 4, lane a, RC-01).
// Run: node scripts/gen-english-bloom.mjs
import fs from "node:fs";
import path from "node:path";
import { bloomIndexes, BLOOM_BYTES } from "../src/lib/thunai/english.hash.mjs";
const words = fs.readFileSync(path.join("node_modules", "word-list", "words.txt"), "utf8").split(/\r?\n/).filter((w) => w.length >= 3 && w.length <= 14);
const bits = new Uint8Array(BLOOM_BYTES);
for (const w of words) for (const i of bloomIndexes(w)) bits[i >> 3] |= 1 << (i & 7);
const out = `// generated by scripts/gen-english-bloom.mjs from the word-list package: do not edit\nexport const ENGLISH_BLOOM = "${Buffer.from(bits).toString("base64")}";\n`;
fs.writeFileSync(path.join("src", "lib", "thunai", "english.bloom.ts"), out);
console.log(words.length, "words,", out.length, "chars");
