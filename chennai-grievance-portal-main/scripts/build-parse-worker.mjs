/**
 * Builds scripts/studio-parse-worker.mjs, the Data Studio's file reader that runs in its own process (src/lib/studio/parse-pool.ts starts it;
 * QA pass 7): src/lib/studio/parse-worker-main.ts and the parse code it imports, bundled into one ES module. SheetJS stays a package
 * import (xlsx.mjs, the build the server bundle uses), so the reader runs the same code as before, only off the server's thread.
 *
 *   node scripts/build-parse-worker.mjs           write the bundle (run it after changing any file the reader imports)
 *   node scripts/build-parse-worker.mjs --check   exit 1 if the bundle is older than the code
 *
 * The bundle is committed, so `next dev`, `next build` + `next start` (Railway) and vitest need no build step of their own.
 * tests/qa/pass7/studio-parse/bundle.test.ts fails while the committed bundle differs from a fresh build.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = path.join(ROOT, "scripts", "studio-parse-worker.mjs");

/** The bundle's text, LF line endings (git may check the file out with CRLF on Windows). */
export async function bundle() {
  const { build } = await import("esbuild");
  const r = await build({
    absWorkingDir: ROOT,
    entryPoints: ["src/lib/studio/parse-worker-main.ts"],
    tsconfig: "tsconfig.json",
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    // packages load from node_modules at run time; the server side of the reader (dynamically imported by parse.ts) never runs in it
    external: ["xlsx", "tesseract.js", "@/lib/studio/parse-pool"],
    write: false,
    legalComments: "none",
    charset: "utf8",
    logLevel: "silent",
    banner: { js: "// Generated by scripts/build-parse-worker.mjs from src/lib/studio/parse-worker-main.ts and what it imports. Do not edit: change the source and run the script.\n// The Data Studio's file reader, run in its own process by src/lib/studio/parse-pool.ts." }
  });
  return r.outputFiles[0].text.replace(/\r\n/g, "\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await bundle();
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : null;
  if (process.argv.includes("--check")) {
    if (now !== text) { console.error(`${path.relative(ROOT, OUT)} is older than the code: run node scripts/build-parse-worker.mjs`); process.exit(1); }
    console.log(`${path.relative(ROOT, OUT)} is up to date`);
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${(text.length / 1024).toFixed(0)} KB)${now === text ? ", unchanged" : ""}`);
  }
}
