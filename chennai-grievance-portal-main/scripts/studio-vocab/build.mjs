// Builds src/lib/studio/vocab.ts: every word in the string and template literals of the files that write the Studio's sentences
// (insights, the brief, drill-downs, plan titles, dates), for ai.ts: the model reads these words, and only these, from a sentence
// the platform computed; any other run of words came from the file and reaches the model as a [value X] token.
//   node scripts/studio-vocab/build.mjs        (re-run after changing a sentence template; tests/qa/pass7/studio-egress checks it)
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..", "..");
const FILES = ["insights.ts", "insights2.ts", "brief.ts", "drill.ts", "dashboard.ts", "types.ts", "values.ts", "rank.ts", "family.ts", "engine.ts", "story.ts"]
  .map((f) => path.join(ROOT, "src", "lib", "studio", f));
// words never let through, whatever a template says: what an instruction to pass on personal data or reach someone would need
const NEVER = new Set(("phone phones mobile mobiles cell call calls called calling ring rang rung dial whatsapp telegram signal email emails mail gmail " +
  "aadhaar aadhar adhar otp password passwords pin voter epic uidai pan ifsc upi bank account accounts address addresses share shared send sent forward " +
  "forwarded collect collected obtain furnish submit post upload link links http https www url contact contacts helpline number numbers " +
  "read reads out give tell provide hand copy copies photo photos document documents form forms write message text reply citizen citizens resident residents " +
  "complainant complainants petitioner petitioners beneficiary beneficiaries register registers list lists names name details personal private identity id ids " +
  "card cards record records login credentials code codes desk relief whatsapp pe bhejo karo do " +
  "zero oh nil one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen " +
  "twenty thirty forty fifty sixty seventy eighty ninety double triple").split(" "));
const words = new Set();
const add = (s) => { for (const w of s.toLowerCase().match(/[a-z]+/g) ?? []) if (!NEVER.has(w)) words.add(w); };
for (const f of FILES) {
  const src = ts.createSourceFile(f, fs.readFileSync(f, "utf8"), ts.ScriptTarget.Latest, true);
  const walk = (n) => {
    if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) add(n.text);
    else if (ts.isTemplateExpression(n)) { add(n.head.text); for (const sp of n.templateSpans) add(sp.literal.text); }
    ts.forEachChild(n, walk);
  };
  walk(src);
}
// the district's zones (names the platform writes), months, and plain connectives the model needs to read a sentence
for (const w of ("thiruvottiyur manali madhavaram tondiarpet royapuram thiru vi ka nagar ambattur anna teynampet kodambakkam valasaravakkam alandur adyar " +
  "perungudi sholinganallur january february march april may june july august september october november december jan feb mar apr jun jul aug sep sept oct nov dec " +
  "a an the of in on at to by for from with and or than as is are was were be been has have had it its this that these those not no all each every per").split(" ")) words.add(w);
const list = [...words].filter((w) => w.length > 0).sort();
const out = `// GENERATED by scripts/studio-vocab/build.mjs from the Studio's sentence templates (${list.length} words). Do not edit by hand.
// The words a model may read in a sentence the platform computed (ai.ts, untrusted.ts forModel): any other run of words came from the file.
export const TEMPLATE_WORDS: ReadonlySet<string> = new Set(${JSON.stringify(list)});
`;
fs.writeFileSync(path.join(ROOT, "src", "lib", "studio", "vocab.ts"), out);
console.log(`${list.length} words`);
