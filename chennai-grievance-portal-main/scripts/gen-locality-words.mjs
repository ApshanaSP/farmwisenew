// Builds src/lib/thunai/areas.localities.ts: every word of the 4,883 locality names of the Corporation's own list (data/gcc-reference/areas-localities.json).
// A word on it is a place of ours, so "Mannady police report" is our police (RC-01). Run: node scripts/gen-locality-words.mjs
import fs from "node:fs";
const j = JSON.parse(fs.readFileSync("data/gcc-reference/areas-localities.json", "utf8"));
const words = new Set();
for (const l of j.localities) for (const w of String(l.name).toLowerCase().split(/[^a-z]+/)) if (w.length >= 4) words.add(w);
const list = [...words].sort();
fs.writeFileSync("src/lib/thunai/areas.localities.ts", `// generated by scripts/gen-locality-words.mjs from data/gcc-reference/areas-localities.json: do not edit\nexport const LOCALITY_WORDS: ReadonlySet<string> = new Set(\n  "${list.join(" ")}".split(" "));\n`);
console.log(list.length);
