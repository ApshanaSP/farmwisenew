// QA pass 5: writes docs/qa/pass5/FINAL_REPORT.md from the raw files, so that no count in it is typed by hand.
//   node tests/qa/pass5/report.mjs
// Reads: docs/qa/pass5/BUGS.json, results/*.summary.json, results/access-matrix-*.json, evidence/{tsc,lint,build}-gate.log, the reviewer's
// and skeptic's verdict files, and git (branch, commits). Prose that is not a count lives in docs/qa/pass5/report-notes.md and is copied in.
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const P5 = path.resolve(APP, "..", "docs", "qa", "pass5");
const rd = (f) => fs.readFileSync(path.join(P5, f), "utf8");
const has = (f) => fs.existsSync(path.join(P5, f));
const json = (f) => JSON.parse(rd(f));
const git = (c) => execSync(`git ${c}`, { cwd: APP, encoding: "utf8" }).trim();

const bugs = json("BUGS.json");
const SEV = ["P0", "P1", "P2", "P3"], ST = ["fixed", "open", "owner"];
const count = (f) => bugs.filter(f).length;
const out = [];
const w = (s = "") => out.push(s);

w("# QA pass 5: final report");
w();
w(`Generated by \`tests/qa/pass5/report.mjs\` at ${new Date().toISOString()} from the files in \`docs/qa/pass5/\`. Every number below is computed from those files.`);
w();
w(`- Branch: \`${git("rev-parse --abbrev-ref HEAD")}\`, commit at generation: \`${git("rev-parse --short HEAD")}\`. Nothing was pushed, merged into main, or opened as a pull request.`);
w(`- Base: main \`d45cf96\` with QA pass 4 (\`7279522\`) merged in \`393bd96\` (see MERGE.md). Commits on this branch since main: ${git("rev-list --count d45cf96..HEAD")} (of them, from pass 4: ${git("rev-list --count d45cf96..7279522")}).`);
w(`- Fix commits in pass 5 (subject starts \`fix(P5-\`): ${git('log --format=%s d45cf96..HEAD').split("\n").filter((s) => /^fix\(P5-/.test(s)).length}; test-only fixes (\`test(P5-\`): ${git('log --format=%s d45cf96..HEAD').split("\n").filter((s) => /^test\(P5-/.test(s)).length}.`);
w();
w("## Bugs by severity and status");
w();
w(`| Severity | ${ST.join(" | ")} | total |`);
w(`|---|${ST.map(() => "---").join("|")}|---|`);
for (const s of SEV) w(`| ${s} | ${ST.map((t) => count((b) => b.severity === s && b.status === t)).join(" | ")} | ${count((b) => b.severity === s)} |`);
w(`| all | ${ST.map((t) => count((b) => b.status === t)).join(" | ")} | ${bugs.length} |`);
w();
w(`Fixed rows with a revert check recorded as passing: ${count((b) => b.status === "fixed" && /^pass/.test(String(b.revert_check ?? "")))} of ${count((b) => b.status === "fixed")}.`);
w(`Fixed rows whose reviewer verdict is recorded: ${count((b) => b.status === "fixed" && b.reviewer)} (see "Review" below).`);
w();
w("| id | sev | status | area | title | fix |");
w("|---|---|---|---|---|---|");
for (const b of bugs) w(`| ${b.id} | ${b.severity} | ${b.status} | ${b.area ?? ""} | ${String(b.title ?? "").replace(/\|/g, "/")} | ${b.fix_commit ?? ""} |`);
w();

w("## Test runs");
w();
w("| run | config | TZ | seed | tests | passed | failed | skipped | seconds |");
w("|---|---|---|---|---|---|---|---|---|");
for (const f of fs.readdirSync(path.join(P5, "results")).filter((f) => f.endsWith(".summary.json")).sort()) {
  const s = json(`results/${f}`);
  w(`| ${s.tag} | ${s.config} | ${s.tz} | ${s.seed} | ${s.numTotalTests} | ${s.numPassedTests} | ${s.numFailedTests} | ${s.numPendingTests} | ${s.secs} |`);
}
w();
for (const f of fs.readdirSync(path.join(P5, "results")).filter((f) => /^suite-gate.*\.summary\.json$/.test(f)).sort()) {
  const s = json(`results/${f}`);
  if (s.failed.length) { w(`Failures in ${s.tag}:`); for (const x of s.failed) w(`- ${x}`); w(); }
}

w("## Access matrix");
w();
for (const f of fs.readdirSync(path.join(P5, "results")).filter((f) => /^access-matrix-.*\.json$/.test(f)).sort()) {
  const m = json(`results/${f}`);
  w(`- \`${f}\` (port ${m.port}, ${m.generated}): ${m.routes} routes, ${m.methods} route-methods, ${m.cells} cells: ${m.summary.pass} pass, ${m.summary.fail} fail, ${m.summary.skip} skip. Data-scope checks: ${m.scopeSummary.pass} pass, ${m.scopeSummary.fail} fail.`);
  for (const c of m.cellList.filter((c) => c.verdict === "fail")) w(`  - FAIL ${c.method} ${c.route} as ${c.identity}: expected ${c.expected}, got ${c.status} (${c.rule})`);
}
w();

w("## Browser drive (gate)");
w();
if (has("results/drive-gate.json")) {
  const d = json("results/drive-gate.json");
  const bad = d.pages.filter((p) => p.status >= 400 || p.status === 0 || p.consoleErrors.length || p.hScroll || (p.axe && (p.axe.critical.length || p.axe.serious.length)));
  const axed = d.pages.filter((p) => p.axe);
  w(`- \`results/drive-gate.json\` (port ${d.port}, ${d.generated}): ${d.pages.length} page loads (5 roles, 360 and 1280 wide), ${bad.length} with a problem; axe on ${axed.length} loads: ${axed.reduce((a, p) => a + p.axe.critical.length, 0)} critical, ${axed.reduce((a, p) => a + p.axe.serious.length, 0)} serious.`);
  for (const p of bad) w(`  - ${p.role} ${p.page} at ${p.width}: status ${p.status}${p.hScroll ? ", sideways scroll" : ""}${p.consoleErrors.length ? `, ${p.consoleErrors.length} console errors` : ""}${p.axe ? `, axe serious: ${p.axe.serious.join(", ") || "none"}` : ""}`);
  const j = d.journey;
  w(`- Petition journey: upload ${j.upload}, reading ${j.readStatus}, approval ${j.approve}, slip number ${j.code ?? "none"}, SMS ${j.sms?.state ?? "?"}; tracking at 360 px shows the status: ${j.trackShowsStatus}, shows personal data: ${j.trackShowsPersonal}, console errors: ${(j.trackConsoleErrors ?? []).length}, wrong last 4 digits answer: ${j.trackWrongLast4}.`);
} else w("- not run");
w();

w("## Gate logs");
w();
for (const [f, label] of [["evidence/tsc-gate.log", "Type check"], ["evidence/lint-gate.log", "Lint"], ["evidence/build-gate.log", "Production build"]]) {
  if (!has(f)) { w(`- ${label}: not run (no \`${f}\`).`); continue; }
  const t = rd(f);
  const exit = (t.match(/EXIT=(\d+)/) ?? [])[1];
  const extra = label === "Lint" ? `, ${(t.match(/ Error: /g) ?? []).length} errors, ${(t.match(/ Warning: /g) ?? []).length} warnings` : label === "Type check" ? `, ${(t.match(/error TS/g) ?? []).length} errors` : "";
  w(`- ${label}: exit ${exit ?? "?"}${extra} (\`${f}\`).`);
}
w();

w("## Review");
w();
w("A fix a reviewer broke went back to step 1; the BUGS.json `reviewer` column says how each break was fixed and revert-checked.");
w();
for (const f of ["findings/reviewer.json", "findings/reviewer2.json", "findings/skeptic.json"]) {
  if (!has(f)) { w(`- \`${f}\`: not present.`); continue; }
  const r = json(f);
  w(`- \`${f}\`: ${r.length} rows.`);
  for (const x of r) w(`  - ${x.id ?? x.commit ?? ""}: ${String(x.verdict ?? x.title ?? "").replace(/\n/g, " ")}`);
}
w();
if (has("report-notes.md")) { w(rd("report-notes.md")); w(); }

fs.writeFileSync(path.join(P5, "FINAL_REPORT.md"), out.join("\n") + "\n");
console.log(`FINAL_REPORT.md: ${out.length} lines, ${bugs.length} bugs`);
