// QA pass 6: writes docs/qa/pass6/FINAL_REPORT.md from the raw files, so that no count in it is typed by hand.
//   node tests/qa/pass6/report.mjs
// Reads: docs/qa/pass6/BUGS.json, findings/*.json, results/*.summary.json, results/access-matrix-*.json, results/drive-gate.json,
// evidence/{tsc,lint,build}-gate.log, docs/qa/pass4/golden/diffs/p6-*.json, and git (branch, commits). Prose that is not a count lives in
// docs/qa/pass6/report-notes.md and is copied in.
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const P6 = path.resolve(APP, "..", "docs", "qa", "pass6");
const GOLD = path.resolve(APP, "..", "docs", "qa", "pass4", "golden");
const BASE = "5c082b7";
const rd = (f) => fs.readFileSync(path.join(P6, f), "utf8");
const has = (f) => fs.existsSync(path.join(P6, f));
const json = (f) => JSON.parse(rd(f));
const git = (c) => execSync(`git ${c}`, { cwd: APP, encoding: "utf8" }).trim();
const list = (dir, re) => (fs.existsSync(path.join(P6, dir)) ? fs.readdirSync(path.join(P6, dir)).filter((f) => re.test(f)).sort() : []);

const bugs = json("BUGS.json");
const SEV = ["P0", "P1", "P2", "P3"], ST = ["fixed", "open", "owner"];
const count = (f) => bugs.filter(f).length;
const out = [];
const w = (s = "") => out.push(s);
const subjects = git(`log --format=%s ${BASE}..HEAD`).split("\n").filter(Boolean);

w("# QA pass 6: final report");
w();
w(`Generated by \`tests/qa/pass6/report.mjs\` at ${new Date().toISOString()} from the files in \`docs/qa/pass6/\`. Every number below is computed from those files.`);
w();
w(`- Branch: \`${git("rev-parse --abbrev-ref HEAD")}\`, commit at generation: \`${git("rev-parse --short HEAD")}\`. Nothing from pass 6 was pushed, merged into main, or opened as a pull request. (Pass 5's branch \`claude/qa-pass5-05abfd\` was pushed to origin by the pass 5 session at the owner's request, at \`3a5a9a2\`, one state commit after \`5c082b7\`, the commit pass 6 starts from. So pass 4 and pass 5 are on origin; pass 6 is not.)`);
w(`- Base: \`${BASE}\` on \`claude/qa-pass5-05abfd\` (main \`d45cf96\` + pass 4 \`7279522\` merged as \`393bd96\` + pass 5's fixes). Commits in pass 6: ${subjects.length}.`);
w(`- Fix commits in pass 6 (subject starts \`fix(\`): ${subjects.filter((s) => /^fix\(/.test(s)).length}; test-only fixes (\`test(\`): ${subjects.filter((s) => /^test\(/.test(s)).length}.`);
w();
w("## Bugs by severity and status");
w();
w("`BUGS.json` holds pass 6's rows (P6-NNN, found and verified by the lead or by a fix's own failing test), pass 5's rows closed in pass 6 (P5-NNN, `closed_in: pass6`), and every hunter's, reviewer's and journey's finding that was not fixed (their own id, `verified` says whether the lead re-ran it).");
w();
w(`| Severity | ${ST.join(" | ")} | total |`);
w(`|---|${ST.map(() => "---").join("|")}|---|`);
for (const s of SEV) w(`| ${s} | ${ST.map((t) => count((b) => b.severity === s && b.status === t)).join(" | ")} | ${count((b) => b.severity === s)} |`);
w(`| all | ${ST.map((t) => count((b) => b.status === t)).join(" | ")} | ${bugs.length} |`);
w();
w(`- Fixed rows: ${count((b) => b.status === "fixed")}, of them pass 5 rows closed here: ${count((b) => b.status === "fixed" && /^P5-/.test(b.id))}; with a revert check recorded: ${count((b) => b.status === "fixed" && String(b.revert_check ?? "").length > 0)}.`);
const agentRow = (b) => !/^P[56]-/.test(b.id);
w(`- Open rows from the agents (their own id): ${count((b) => b.status === "open" && agentRow(b))}, of them re-run by the lead: ${count((b) => b.status === "open" && agentRow(b) && b.verified === true)}. Open P6 rows (the lead's own, re-run): ${count((b) => b.status === "open" && /^P6-/.test(b.id))}. Pass 5 rows carried open: ${count((b) => b.status === "open" && /^P5-/.test(b.id))}.`);
w();
w("| id | sev | status | area | title | fix |");
w("|---|---|---|---|---|---|");
for (const b of bugs) w(`| ${b.id} | ${b.severity} | ${b.status} | ${String(b.area ?? "").replace(/\|/g, "/")} | ${String(b.title ?? "").replace(/\|/g, "/").replace(/\n/g, " ")} | ${b.fix_commit ?? ""} |`);
w();

w("## Findings files (agents)");
w();
w("| file | rows | P0 | P1 | P2 | P3 | fixed (by a P6 row) |");
w("|---|---|---|---|---|---|---|");
for (const f of list("findings", /\.json$/)) {
  const a = json(`findings/${f}`);
  const rows = Array.isArray(a) ? a : [];
  const fixedBy = rows.filter((x) => bugs.some((b) => b.status === "fixed" && String(b.found_by ?? "").includes(String(x.id)))).length;
  w(`| ${f} | ${rows.length} | ${SEV.map((s) => rows.filter((x) => x.severity === s).length).join(" | ")} | ${fixedBy} |`);
}
w();

w("## Test runs");
w();
w("| run | config | TZ | seed | tests | passed | failed | skipped | seconds |");
w("|---|---|---|---|---|---|---|---|---|");
for (const f of list("results", /\.summary\.json$/)) {
  const s = json(`results/${f}`);
  w(`| ${s.tag} | ${s.config} | ${s.tz} | ${s.seed} | ${s.numTotalTests} | ${s.numPassedTests} | ${s.numFailedTests} | ${s.numPendingTests} | ${s.secs} |`);
}
w();
for (const f of list("results", /^suite-(gate|future).*\.summary\.json$/)) {
  const s = json(`results/${f}`);
  if (s.failed.length) { w(`Failures in ${s.tag}:`); for (const x of s.failed) w(`- ${x}`); w(); }
}

w("## Access matrix");
w();
for (const f of list("results", /^access-matrix-.*\.json$/)) {
  const m = json(`results/${f}`);
  w(`- \`${f}\` (port ${m.port}, ${m.generated}): ${m.routes} routes, ${m.methods} route-methods, ${m.cells} cells: ${m.summary.pass} pass, ${m.summary.fail} fail, ${m.summary.skip} skip. Data-scope checks: ${m.scopeSummary.pass} pass, ${m.scopeSummary.fail} fail.`);
  if (m.denyProof) w(`  - Deny cells passing: ${m.denyProof.denyPassing}; proven by the guard's own 401/403: ${m.denyProof.guard}; another 4xx (not proven): ${m.denyProof.unproven} in ${m.denyProof.unprovenMethods.length} methods: ${m.denyProof.unprovenMethods.join("; ")}.`);
  for (const c of m.cellList.filter((c) => c.verdict === "fail")) w(`  - FAIL ${c.method} ${c.route} as ${c.identity}: expected ${c.expected}, got ${c.status} (${c.rule})`);
}
w();

w("## Golden master");
w();
for (const f of (fs.existsSync(GOLD) ? fs.readdirSync(GOLD) : []).filter((f) => /^p6-.*\.manifest\.json$/.test(f)).sort()) {
  const m = JSON.parse(fs.readFileSync(path.join(GOLD, f), "utf8"));
  const reqs = Array.isArray(m.requests) ? m.requests : [];
  w(`- \`docs/qa/pass4/golden/${f}\` (${m.head?.label ?? f}, Next build ${m.head?.next_build_id ?? "?"}): ${reqs.length} requests recorded, ${reqs.filter((r) => Number(r.status) >= 500).length} with a 5xx status.`);
}
const diffs = fs.existsSync(path.join(GOLD, "diffs")) ? fs.readdirSync(path.join(GOLD, "diffs")).filter((f) => /^p6-.*\.json$/.test(f)).sort() : [];
for (const f of diffs) {
  const d = JSON.parse(fs.readFileSync(path.join(GOLD, "diffs", f), "utf8"));
  const changed = d.changed ?? d.summary?.changed ?? (Array.isArray(d.diffs) ? d.diffs.length : "?");
  w(`- \`docs/qa/pass4/golden/diffs/${f}\`: ${typeof changed === "number" ? changed : JSON.stringify(changed).slice(0, 80)} changed requests${d.added != null ? `, ${d.added} added, ${d.removed} removed` : ""}. The explanation of each is in \`docs/qa/pass6/evidence/golden-explained.md\`.`);
}
w();

w("## Browser drive (gate)");
w();
if (has("results/drive-gate.json")) {
  const d = json("results/drive-gate.json");
  const bad = d.pages.filter((p) => p.status >= 400 || p.status === 0 || p.consoleErrors.length || p.hScroll || (p.axe && (p.axe.critical.length || p.axe.serious.length)));
  const axed = d.pages.filter((p) => p.axe);
  w(`- \`results/drive-gate.json\` (port ${d.port}, ${d.generated}): ${d.pages.length} page loads (5 roles, 360 and 1280 wide), ${bad.length} with a problem; axe on ${axed.length} loads: ${axed.reduce((a, p) => a + p.axe.critical.length, 0)} critical, ${axed.reduce((a, p) => a + p.axe.serious.length, 0)} serious.`);
  for (const p of bad) w(`  - ${p.role} ${p.page} at ${p.width}: status ${p.status}${p.hScroll ? ", sideways scroll" : ""}${p.consoleErrors.length ? `, ${p.consoleErrors.length} console errors` : ""}${p.axe ? `, axe serious: ${p.axe.serious.join(", ") || "none"}` : ""}`);
  const j = d.journey;
  w(`- Petition journey: upload ${j.upload}, reading ${j.readStatus}, approval ${j.approve}, slip number ${j.code ? "issued" : "none"}, SMS ${j.sms?.state ?? "?"}; tracking at 360 px shows the status: ${j.trackShowsStatus}, shows personal data: ${j.trackShowsPersonal}.`);
} else w("- not run");
w();

w("## Gate logs");
w();
for (const [f, label] of [["evidence/tsc-gate.log", "Type check"], ["evidence/lint-gate.log", "Lint"], ["evidence/build-gate.log", "Production build"]]) {
  if (!has(f)) { w(`- ${label}: not run (no \`${f}\`).`); continue; }
  const t = rd(f);
  const exit = (t.match(/EXIT=(\d+)/) ?? [])[1];
  const extra = label === "Lint" ? `, ${(t.match(/ Error: /g) ?? []).length} errors, ${(t.match(/ Warning: /g) ?? []).length} warnings` : label === "Type check" ? `, ${(t.match(/error TS/g) ?? []).length} errors` : "";
  w(`- ${label}: exit ${exit ?? "?"}${extra} (\`${f}\`).`);
}
w();
if (has("report-notes.md")) { w(rd("report-notes.md")); w(); }

fs.writeFileSync(path.join(P6, "FINAL_REPORT.md"), out.join("\n") + "\n");
console.log(`FINAL_REPORT.md: ${out.length} lines, ${bugs.length} bugs`);
