import { call } from "../../lib/live.mjs";
import { snap, CH } from "./snap.mjs";
import { confirmed } from "./confirm.mjs";
const id = process.argv[2];
const res = await confirmed("collector", "POST", "/api/collector/decisions", { incidentIds: [id], decision: "escalate", escalateTo: "GCC-ELE", note: "QA hunt2: this is a street-light issue, send to Electrical" }, CH.headers);
console.log("escalate", res.first, res.confirm, res.r.status, res.r.text.slice(0, 300));
console.log(JSON.stringify(await snap(id, "after escalate to GCC-ELE")));
const b = await call(3106, "officerB", "GET", `/api/officer/grievances/${id}`);
console.log("officerB (GCC-ELE) detail", b.status, b.text.slice(0, 120));
const bl = JSON.parse((await call(3106, "officerB", "GET", `/api/officer/grievances?tab=all&period=quarterly&q=${id}`)).text);
console.log("officerB queue all tab total", bl.total);
const bs = await call(3106, "officerB", "GET", `/api/officer/search?q=${id}`);
console.log("officerB search", bs.status, bs.text.slice(0, 200));
const a = JSON.parse((await call(3106, "officerA", "GET", `/api/officer/grievances/${id}`)).text);
console.log("officerA timeline tail", JSON.stringify(a.timeline.slice(-1)), "stage", a.grievance.stage);
const cl = JSON.parse((await call(3106, "collector", "GET", `/api/collector/list?scope=all&q=${id}`, CH)).text);
console.log("collector list dept", cl.rows[0]?.dept, cl.rows[0]?.dept_name, "status", cl.rows[0]?.status);
const ov = JSON.parse((await call(3106, "collector", "GET", `/api/collector/overview?period=weekly&dept=GCC-ELE`, CH)).text);
const ovA = JSON.parse((await call(3106, "collector", "GET", `/api/collector/overview?period=weekly&dept=GCC-SWM`, CH)).text);
console.log("Collector weekly ongoing GCC-ELE", ov.kpi.cur.ongoing, "GCC-SWM", ovA.kpi.cur.ongoing);
