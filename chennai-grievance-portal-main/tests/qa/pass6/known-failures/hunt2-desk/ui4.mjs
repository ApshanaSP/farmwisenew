import { createRequire } from "node:module";
import path from "node:path";
import { signIn } from "../../lib/live.mjs";
const require = createRequire(import.meta.url);
const { chromium } = require("@playwright/test");
const B = "http://127.0.0.1:3106", P = 3106, ID = process.argv[2] || "1000000024";
const EV = path.resolve("..", "docs", "qa", "pass6", "evidence", "hunt2-desk");
const out = {};
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 360, height: 780 }, baseURL: B, isMobile: true });
const cookie = await signIn(P, "manu"); await ctx.addCookies(cookie.split("; ").map((c) => { const i = c.indexOf("="); return { name: c.slice(0, i), value: c.slice(i + 1), url: B }; }));
const page = await ctx.newPage();
const errs = []; page.on("console", (m) => { if (m.type() === "error") errs.push(m.text().slice(0, 150)); }); page.on("pageerror", (e) => errs.push("pageerror " + e.message.slice(0, 150)));
await page.goto("/officer", { waitUntil: "networkidle", timeout: 90000 });
await page.getByText(`Petition ${ID}`).first().click();
await page.waitForSelector("form.mn-form", { timeout: 20000 });
const form = page.locator("form.mn-form");
const inp = (label) => form.locator(".mn-grid > *").filter({ hasText: label }).locator("input,select").first();
await inp("Name").fill("ராணி எஸ்");
await inp("Mobile").pressSequentially("+91 98400 12345");
out.mobileAfterTyping = await inp("Mobile").inputValue();
await inp("Mobile").fill("");
await page.evaluate(() => navigator.clipboard?.writeText?.("098400 12345").catch(() => {}));
await inp("Street").fill("ஜவஹர் தெரு");
await inp("Ward").fill("70");
await inp("Department").selectOption("CMWSSB");
await inp("The problem, in one line").fill("கழிவுநீர் தெருவில் ஓடுகிறது");
await page.waitForTimeout(2500);
out.hScroll = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
out.wide = await page.evaluate(() => [...document.querySelectorAll("body *")].filter((e) => { const r = e.getBoundingClientRect(); return r.width > 0 && r.right > window.innerWidth + 2 && getComputedStyle(e).position !== "fixed"; }).slice(0, 6).map((e) => e.tagName + "." + String(e.className).slice(0, 40) + " r=" + Math.round(e.getBoundingClientRect().right)));
out.came = await form.locator(".mn-came").innerText().catch(() => null);
out.errs = errs;
await page.screenshot({ path: path.join(EV, "desk-form-360.png"), fullPage: true });
await browser.close();
console.log(JSON.stringify(out, null, 1).slice(0, 3000));
