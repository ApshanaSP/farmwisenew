// the desk's own screen: "Add to this case" on a Metrowater case, then the department changed to Solid Waste and approved at once
import { createRequire } from "node:module";
import path from "node:path";
import { signIn } from "../../lib/live.mjs";
import { upload, file, base, mob, call, j } from "./h.mjs";
const require = createRequire(import.meta.url);
const { chromium } = require("@playwright/test");
const B = "http://127.0.0.1:3106", P = 3106;
const EV = path.resolve("..", "docs", "qa", "pass6", "evidence", "hunt2-desk");
const out = {};
const M = mob();
const X = await upload();
const fx = await file(X.id, base({ name: "Anbu Selvan", mobile: M, problem: "Sewage overflowing near the bus stop", dept: "CMWSSB", ward: 70, street: "Jawahar Street" }));
out.X = fx.body.approved?.code;
const Y = await upload(); out.Y = Y.id;
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, baseURL: B });
const cookie = await signIn(P, "manu"); await ctx.addCookies(cookie.split("; ").map((c) => { const i = c.indexOf("="); return { name: c.slice(0, i), value: c.slice(i + 1), url: B }; }));
const page = await ctx.newPage();
await page.goto("/officer", { waitUntil: "networkidle", timeout: 90000 });
await page.getByText(`Petition ${Y.id}`, { exact: false }).first().click();
await page.waitForSelector("form.mn-form", { timeout: 20000 });
const form = page.locator("form.mn-form");
const inp = (label) => form.locator(".mn-grid > *").filter({ hasText: label }).locator("input,select").first();
await inp("Name").fill("Anbu Selvan");
await inp("Mobile").fill(M);
await inp("Street").fill("Jawahar Street");
await inp("Ward").fill("70");
await inp("Department").selectOption("CMWSSB");
await inp("The problem, in one line").fill("Sewage overflowing near the bus stop again");
await page.waitForSelector("text=Add to this case", { timeout: 15000 });
out.cameBefore = (await form.locator(".mn-came").innerText()).slice(0, 300);
await form.getByRole("button", { name: "Add to this case" }).first().click();
out.btnBefore = await form.locator("button.mn-primary").innerText();
await inp("Department").selectOption("GCC-SWM");
out.btnAfterDeptChange = await form.locator("button.mn-primary").innerText();
await form.locator("button.mn-primary").click();
await page.waitForTimeout(4000);
out.after = (await page.locator("body").innerText()).match(/(Petition approved[^\n]*|Approved[^\n]*)/)?.[0] ?? null;
await page.screenshot({ path: path.join(EV, "desk-attach-other-dept.png") });
await browser.close();
const d = j(await call(P, "manu", "GET", `/api/manu/petitions/${Y.id}`));
out.Yapproved = d.approved;
console.log(JSON.stringify(out, null, 1));
