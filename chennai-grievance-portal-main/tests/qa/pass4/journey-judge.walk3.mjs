// journey-judge walk 3: periods, cross-filter, evidence, search, Ask District IQ, menu. node tests/qa/pass4/journey-judge.walk3.mjs
import { chromium } from "playwright";
import fs from "node:fs";
const base = "http://localhost:3180", D = "../docs/qa/pass4/evidence/journeys/judge/";
const { accounts } = await import("../seed-local-users.mjs");
const acc = accounts().find((x) => x.key === "collector");
const br = await chromium.launch({ args: ["--mute-audio"] });
const page = await (await br.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errs = [];
page.on("console", (m) => { if (m.type() === "error") errs.push(m.text().slice(0, 200)); });
page.on("pageerror", (e) => errs.push("PAGEERROR " + String(e).slice(0, 200)));
page.on("response", (r) => { if (r.status() >= 400) errs.push(`HTTP ${r.status()} ${r.url().slice(0, 120)}`); });
await page.goto(base + "/login", { waitUntil: "networkidle" });
await page.locator("input[type=email]").first().fill(acc.email);
await page.locator("input[type=password]").first().fill(acc.password);
await page.getByRole("button", { name: /^Sign in$/ }).click();
await page.waitForURL(/\/collector/, { timeout: 60000 });
await page.waitForTimeout(8000);
const body = async () => (await page.locator("body").innerText());
const snap = async (name, wait = 2500) => {
  await page.waitForTimeout(wait);
  await page.screenshot({ path: D + name + ".png" });
  const t = await body();
  fs.writeFileSync(D + name + ".txt", t.slice(0, 9000));
  console.log("==", name, "errs", errs.length, "\n", t.replace(/\n+/g, " | ").slice(0, 600));
};
const step = async (name, fn, wait) => { try { await fn(); await snap(name, wait); } catch (e) { console.log("FAIL", name, e.message.split("\n")[0].slice(0, 150)); await page.screenshot({ path: D + name + "-FAIL.png" }); } };
const click = (t) => page.getByText(t, { exact: true }).first().click({ timeout: 8000 });
for (const p of ["Weekly", "Monthly", "Quarterly"]) await step("04-overview-" + p, () => click(p), 4000);
await step("05-back-daily", () => click("Daily"));
await step("06-click-severe-tile", () => click("Severe"));
await step("07-click-zone-Madhavaram", () => page.locator("text=MADHAVARAM").first().click({ timeout: 8000 }));
await step("08-open-incident", () => page.getByText(/School van driver arrested for sexu/).first().click({ timeout: 8000 }), 4000);
await step("09-menu", () => click("Menu"));
await page.keyboard.press("Escape");
await step("10-search-open", async () => { await page.keyboard.press("/"); });
await step("11-search-query", async () => { await page.keyboard.type("incidents reported by more than one newspaper but missing from the departmental application", { delay: 5 }); await page.keyboard.press("Enter"); }, 8000);
fs.writeFileSync(D + "errs3.json", JSON.stringify(errs, null, 1));
await br.close();
