// journey-judge: real-user walk of the Collector console. node tests/qa/pass4/journey-judge.walk.mjs [port]
import { chromium } from "playwright";
import fs from "node:fs";
const port = process.argv[2] || 3180, base = `http://localhost:${port}`;
const D = "../docs/qa/pass4/evidence/journeys/judge/";
const br = await chromium.launch({ args: ["--mute-audio"] });
const { accounts } = await import("../seed-local-users.mjs");
const acc = accounts().find((x) => x.key === "collector");
const ctx = await br.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
const errs = [];
page.on("console", (m) => { if (m.type() === "error") errs.push(m.text().slice(0, 200)); });
page.on("pageerror", (e) => errs.push("PAGEERROR " + String(e).slice(0, 200)));
page.on("response", (r) => { if (r.status() >= 400) errs.push(`HTTP ${r.status()} ${r.url().slice(0, 120)}`); });
await page.goto(base + "/login", { waitUntil: "networkidle", timeout: 45000 });
await page.screenshot({ path: D + "00-login.png" });
await page.getByRole("button", { name: /Collector/ }).first().click().catch(() => {});
await page.locator('input[type=email],input[name=email]').first().fill(acc.email);
await page.locator('input[type=password]').first().fill(acc.password);
await page.getByRole("button", { name: /^Sign in$/ }).click();
await page.waitForURL(/collector/, { timeout: 45000 }).catch((e) => errs.push("LOGIN " + e.message));
await page.waitForLoadState("networkidle").catch(() => {}); for (let i = 0; i < 12; i++) { await page.waitForTimeout(5000); if (!/login/.test(page.url())) break; } console.log("URL", page.url()); await page.waitForTimeout(8000);
await page.waitForTimeout(3000);
await page.screenshot({ path: D + "01-home.png" });
fs.writeFileSync(D + "01-home.txt", (await page.locator("body").innerText()).slice(0, 6000));
fs.writeFileSync(D + "01-buttons.json", JSON.stringify(await page.$$eval("button,a,[role=tab]", (els) => els.map((e) => (e.innerText || e.getAttribute("aria-label") || "").trim().slice(0, 40)).filter(Boolean)), null, 0));
fs.writeFileSync(D + "errs.json", JSON.stringify(errs, null, 1));
console.log(await page.title(), errs);
await br.close();
