#!/usr/bin/env python3
"""Tamil ASR held-out clips from OpenSLR SLR65 (CC BY-SA 4.0: test only, never shipped; only hashes are committed).
60 clean + 40 noisy, chosen by the hash of the file name. The noise is generated here, labelled as such: babble mixed from
8 OTHER clips plus pink noise, at 10 dB SNR. MUSAN (11 GB) is not downloaded.

  python -I eval/holdout/tamil-asr/prepare.py <ta_in_female.zip> <out_dir>
Writes <out_dir>/*.wav (16 kHz mono 16-bit) and eval/holdout/tamil-asr/manifest.json.
"""
import array, hashlib, io, json, math, os, random, sys, wave, zipfile

zip_path, out_dir = sys.argv[1], sys.argv[2]
here = os.path.dirname(os.path.abspath(__file__))
os.makedirs(out_dir, exist_ok=True)
z = zipfile.ZipFile(zip_path)
names = z.namelist()
tsv = next(n for n in names if n.endswith("line_index.tsv"))
lines = {}
for row in z.read(tsv).decode("utf8").splitlines():
    a, _, b = row.partition("\t")
    if a and b.strip():
        lines[a.strip()] = b.strip()
wavs = {os.path.basename(n)[:-4]: n for n in names if n.endswith(".wav")}
ids = sorted((i for i in lines if i in wavs), key=lambda i: hashlib.sha256(i.encode()).hexdigest())
print("clips", len(ids))


def read16k(name):
    with wave.open(io.BytesIO(z.read(wavs[name]))) as w:
        rate, ch, width, n = w.getframerate(), w.getnchannels(), w.getsampwidth(), w.getnframes()
        raw = w.readframes(n)
    assert width == 2, width
    x = array.array("h")
    x.frombytes(raw)
    if ch > 1:
        x = array.array("h", x[::ch])
    r = rate / 16000
    m = int(len(x) / r)
    out = [0.0] * m
    for i in range(m):
        a, b = int(i * r), max(int(i * r) + 1, min(len(x), int((i + 1) * r)))
        out[i] = sum(x[a:b]) / (b - a) / 32768.0
    return out


def write(path, x):
    peak = max(1.0, max((abs(v) for v in x), default=1.0))
    pcm = array.array("h", (int(max(-1, min(1, v / peak)) * 32767) for v in x))
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(16000)
        w.writeframes(pcm.tobytes())
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def pink(n, rnd):
    # Voss-McCartney with a few octaves is enough for a background
    b = [0.0] * 6
    out = []
    for _ in range(n):
        w = rnd.uniform(-1, 1)
        b[0] = 0.997 * b[0] + 0.029 * w
        b[1] = 0.985 * b[1] + 0.033 * w
        b[2] = 0.950 * b[2] + 0.097 * w
        b[3] = 0.850 * b[3] + 0.196 * w
        b[4] = 0.620 * b[4] + 0.300 * w
        b[5] = 0.250 * b[5] + 0.330 * w
        out.append(sum(b))
    return out


def rms(x):
    return math.sqrt(sum(v * v for v in x) / max(1, len(x))) or 1e-9


usable = [i for i in ids if 12 <= len(lines[i]) <= 160]
clean, noisy, others = usable[:60], usable[60:100], usable[100:108]
rnd = random.Random(20261104)
print("loading babble from", len(others), "other clips")
sources = [read16k(i) for i in others]
items = []
for i in clean:
    h = write(os.path.join(out_dir, f"{i}.wav"), read16k(i))
    items.append({"id": i, "file": f"{i}.wav", "kind": "clean", "sha256": h, "text": lines[i]})
for i in noisy:
    x = read16k(i)
    n = len(x)
    bg = [0.0] * n
    for s in sources:
        off = rnd.randrange(max(1, len(s) - 1))
        for k in range(n):
            bg[k] += s[(off + k) % len(s)]
    p = pink(n, rnd)
    pr, br = rms(p), rms(bg)
    mix = [bg[k] / br + 0.5 * p[k] / pr for k in range(n)]
    g = rms(x) / rms(mix) / (10 ** (10 / 20))
    y = [x[k] + g * mix[k] for k in range(n)]
    h = write(os.path.join(out_dir, f"{i}_noisy.wav"), y)
    items.append({"id": f"{i}_noisy", "file": f"{i}_noisy.wav", "kind": "noisy", "sha256": h, "text": lines[i]})
manifest = {
    "source": "OpenSLR SLR65 ta_in_female.zip",
    "licence": "CC BY-SA 4.0, test only, not redistributed; only hashes and reference text for scoring",
    "noise": "synthetic babble from 8 other SLR65 clips plus pink noise at 10 dB SNR (generated by prepare.py, not a recording)",
    "rate": 16000,
    "items": items,
}
with open(os.path.join(here, "manifest.json"), "w", encoding="utf8") as f:
    json.dump(manifest, f, ensure_ascii=False, indent=0)
print("clean", len(clean), "noisy", len(noisy))
